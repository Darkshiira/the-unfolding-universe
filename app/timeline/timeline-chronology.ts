// Monoton, styckvis linjär hybridtidsskala: vetenskaplig ordning,
// men successivt mer utrymme åt geologiskt yngre händelser.
// [miljoner år före nutid, horisontell position i världskoordinater]
const ANCHORS: readonly (readonly [number, number])[] = [
  [4600, 100],
  [4000, 1100],
  [2500, 2400],
  [1000, 3500],
  [538.8, 4500],
  [251.902, 5400],
  [66, 6200],
  [20, 6700],
  [2.6, 7200],
  [0.3, 7500],
  [0.012, 7770],
  [0.005, 8400],
  [0.001, 9500],
  [0.0005, 10100],
  [0.00025, 10700],
  [0.0001, 11300],
  [0, 12000],
];

export function ageToX(ageMa: number): number {
  const age = Math.max(0, Math.min(4600, ageMa));
  for (let i = 0; i < ANCHORS.length - 1; i++) {
    const [older, left] = ANCHORS[i];
    const [younger, right] = ANCHORS[i + 1];
    if (age <= older && age >= younger) {
      const fraction = (older - age) / (older - younger);
      return left + fraction * (right - left);
    }
  }
  return 12000;
}
